import { Router } from 'express';
import {
  emailRequestSchema,
  loginSchema,
  registerSchema,
  sessionIdSchema,
  verifyEmailSchema,
  forgotPasswordSchema,
  resetPasswordSchema,
  changePasswordSchema,
  mfaSetupSchema,
  mfaConfirmSchema,
  mfaChallengeSchema,
  mfaDisableSchema,
  mfaRegenerateSchema,
} from '@kaaryasthan/shared';
import { validateBody, validateParams } from '../../middleware/validate.js';
import { authRateLimit } from '../../middleware/auth-rate-limit.js';
import { issueCsrf, requireCsrf } from '../../middleware/auth-csrf.js';
import { requireAuth } from '../../middleware/auth-session.js';
import * as controller from './controller.js';
import { registerRoute } from '../../middleware/route-policy.js';

const publicPolicy = { kind: 'public' } as const;
const accountPolicy = { kind: 'account' } as const;

export const authRoutes = Router();
authRoutes.use((_request, response, next) => {
  response.setHeader('Cache-Control', 'private, no-store');
  response.vary('Origin');
  next();
});
registerRoute(
  authRoutes,
  'get',
  '/csrf',
  publicPolicy,
  authRateLimit,
  issueCsrf,
);
registerRoute(
  authRoutes,
  'post',
  '/register',
  publicPolicy,
  authRateLimit,
  requireCsrf,
  validateBody(registerSchema),
  controller.register,
);
registerRoute(
  authRoutes,
  'post',
  '/verify-email/resend',
  publicPolicy,
  authRateLimit,
  requireCsrf,
  validateBody(emailRequestSchema),
  controller.resend,
);
registerRoute(
  authRoutes,
  'post',
  '/verify-email',
  publicPolicy,
  authRateLimit,
  requireCsrf,
  validateBody(verifyEmailSchema),
  controller.verifyEmail,
);
registerRoute(
  authRoutes,
  'post',
  '/login',
  publicPolicy,
  authRateLimit,
  requireCsrf,
  validateBody(loginSchema),
  controller.login,
);
registerRoute(
  authRoutes,
  'post',
  '/refresh',
  publicPolicy,
  authRateLimit,
  requireCsrf,
  controller.refresh,
);
registerRoute(
  authRoutes,
  'post',
  '/logout',
  publicPolicy,
  authRateLimit,
  requireCsrf,
  controller.logout,
);
registerRoute(
  authRoutes,
  'post',
  '/forgot-password',
  publicPolicy,
  authRateLimit,
  requireCsrf,
  validateBody(forgotPasswordSchema),
  controller.forgotPassword,
);
registerRoute(
  authRoutes,
  'post',
  '/reset-password',
  publicPolicy,
  authRateLimit,
  requireCsrf,
  validateBody(resetPasswordSchema),
  controller.resetPassword,
);
registerRoute(
  authRoutes,
  'post',
  '/change-password',
  accountPolicy,
  authRateLimit,
  requireCsrf,
  requireAuth,
  validateBody(changePasswordSchema),
  controller.changePassword,
);
registerRoute(
  authRoutes,
  'post',
  '/2fa/setup',
  accountPolicy,
  authRateLimit,
  requireCsrf,
  requireAuth,
  validateBody(mfaSetupSchema),
  controller.setupMfa,
);
registerRoute(
  authRoutes,
  'post',
  '/2fa/setup/confirm',
  accountPolicy,
  authRateLimit,
  requireCsrf,
  requireAuth,
  validateBody(mfaConfirmSchema),
  controller.confirmMfa,
);
registerRoute(
  authRoutes,
  'post',
  '/2fa/challenge',
  publicPolicy,
  authRateLimit,
  requireCsrf,
  validateBody(mfaChallengeSchema),
  controller.challengeMfa,
);
registerRoute(
  authRoutes,
  'post',
  '/2fa/disable',
  accountPolicy,
  authRateLimit,
  requireCsrf,
  requireAuth,
  validateBody(mfaDisableSchema),
  controller.disableMfa,
);
registerRoute(
  authRoutes,
  'post',
  '/2fa/recovery-codes/regenerate',
  accountPolicy,
  authRateLimit,
  requireCsrf,
  requireAuth,
  validateBody(mfaRegenerateSchema),
  controller.regenerateMfa,
);
registerRoute(
  authRoutes,
  'get',
  '/me',
  accountPolicy,
  authRateLimit,
  requireAuth,
  controller.me,
);
registerRoute(
  authRoutes,
  'get',
  '/sessions',
  accountPolicy,
  authRateLimit,
  requireAuth,
  controller.sessions,
);
registerRoute(
  authRoutes,
  'delete',
  '/sessions/:sessionId',
  accountPolicy,
  authRateLimit,
  requireCsrf,
  requireAuth,
  validateParams(sessionIdSchema),
  controller.revoke,
);
